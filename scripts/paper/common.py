def cell_size(cell):
    m = re.search(r"_(\d+[MB])$", cell)
    return m.group(1) if m else ""


def cell_scene(cell):
    return cell[: -len(cell_size(cell)) - 1] if cell_size(cell) else cell


def size_points(label):
    return int(label[:-1]) * (10**9 if label.endswith("B") else 10**6)


def geomean(values):
    values = [v for v in values if v is not None and v > 0 and math.isfinite(v)]
    return math.exp(sum(map(math.log, values)) / len(values)) if values else float("nan")


def finite(values):
    return [v for v in values if v is not None and isinstance(v, (int, float)) and math.isfinite(v)]


def read_csv(path):
    with open(path, newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def fmt(value, digits=3, dash="--"):
    """A number for a table cell; nan and None become a dash."""
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return dash
    if isinstance(value, int):
        return f"{value:d}"
    return f"{value:.{digits}f}"


def fmt_range(values, digits=2):
    values = finite(values)
    return f"{min(values):.{digits}f}--{max(values):.{digits}f}" if values else "--"


def tex(text):
    """Escape the characters LaTeX treats specially in plain text."""
    return re.sub(r"([&%$#_{}])", r"\\\1", str(text))


def thousands(n):
    return f"{int(n):,}".replace(",", "\\,")


class Table:
    """A booktabs tabular written to paper/generated/<name>.tex. The caption and label live in the
    section that inputs the file, so the generated file holds only the tabular."""

    def __init__(self, name, columns, align=None, note=None):
        self.name, self.columns, self.rows, self.note = name, columns, [], note
        self.align = align or ("l" + "r" * (len(columns) - 1))
        self.midrules = set()

    def add(self, *cells):
        assert len(cells) == len(self.columns), f"{self.name}: {len(cells)} cells for {len(self.columns)} columns"
        self.rows.append([str(c) for c in cells])

    def midrule(self):
        self.midrules.add(len(self.rows))

    def render(self):
        lines = [f"% generated by scripts/paper/tables.py; do not edit", f"\\begin{{tabular}}{{{self.align}}}", "\\toprule",
                 " & ".join(self.columns) + " \\\\", "\\midrule"]
        for i, row in enumerate(self.rows):
            if i in self.midrules and i:
                lines.append("\\midrule")
            lines.append(" & ".join(row) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        return "\n".join(lines) + "\n"

    def write(self):
        GENERATED.mkdir(parents=True, exist_ok=True)
        path = GENERATED / f"{self.name}.tex"
        path.write_text(self.render(), encoding="utf-8")
        return path


class Macros:
    """Named numbers for the prose: \\newcommand{\\name}{value} in numbers.tex, with the source of each
    value in numbers.md. Names are letters only (LaTeX), so counts are spelled out in camel case."""

    def __init__(self):
        self.items = []

    def add(self, name, value, source, digits=3, unit=""):
        assert re.fullmatch(r"[A-Za-z]+", name), f"macro name must be letters only: {name}"
        text = fmt(value, digits) if isinstance(value, (int, float)) else str(value)
        self.items.append((name, text + unit, source))

    def write(self):
        GENERATED.mkdir(parents=True, exist_ok=True)
        tex_lines = ["% generated by scripts/paper/macros.py; do not edit. One macro per measured number."]
        md_lines = ["# Numbers used in the manuscript", "", "| macro | value | source |", "|---|---|---|"]
        for name, text, source in self.items:
            tex_lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
            md_lines.append(f"| `\\{name}` | {text} | {source} |")
        (GENERATED / "numbers.tex").write_text("\n".join(tex_lines) + "\n", encoding="utf-8")
        (GENERATED / "numbers.md").write_text("\n".join(md_lines) + "\n", encoding="utf-8")
        return len(self.items)
